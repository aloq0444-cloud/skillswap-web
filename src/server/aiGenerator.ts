import { DOMAIN_SUBJECTS, DomainSubject } from '../data/domainKnowledge';

interface MessageHistoryItem {
  role: string;
  content: string;
}

// Find matched domain subjects from text
export function findMatchingSubjects(text: string): DomainSubject[] {
  const lower = text.toLowerCase();
  const matched: DomainSubject[] = [];

  for (const subject of DOMAIN_SUBJECTS) {
    if (subject.keywords.some((kw) => lower.includes(kw))) {
      matched.push(subject);
    }
  }

  return matched;
}

// Helper to extract clean query keywords
function cleanQuery(text: string): string {
  return text
    .replace(/[?!.,;:«»"']/g, '')
    .trim();
}

